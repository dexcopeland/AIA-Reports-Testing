import type { ChoiceDef, ItemStatus, StatementDef } from "./types";

type Flag = "gate" | "date" | "ev" | "evopt";

function choice(
  value: string,
  text: string,
  status: ItemStatus,
  mitigation: string | null,
  flag?: Flag,
): ChoiceDef {
  const row: ChoiceDef = { value, text, status, mitigation };
  if (flag === "gate") row.setsGate = "G4";
  if (flag === "date") row.asks = "target_date";
  if (flag === "ev") {
    row.asks = "evidence";
    row.evidenceRequired = true;
  }
  if (flag === "evopt") {
    row.asks = "evidence";
    row.evidenceRequired = false;
  }
  return row;
}

function unknownChoice(status: ItemStatus, mitigation: string | null): ChoiceDef {
  return {
    value: "unknown",
    text: "We don't know / not determined yet",
    status,
    mitigation,
  };
}

function define(item: Omit<StatementDef, "proposed" | "choices"> & { rows: ChoiceDef[] }): StatementDef {
  return {
    ...item,
    proposed: true,
    choices: [...item.rows, unknownChoice(item.unknownStatus, item.unknownMitigation)],
  };
}

